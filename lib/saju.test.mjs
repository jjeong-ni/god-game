// - 일진: 한국천문연구원 음양력 변환 (astro.kasi.re.kr/life/solc?yyyy=&mm=&dd= → LUNC_ILJIN), 2026-10-22 조회
// - 절입 시각(UTC): 영문 위키백과 Lichun / Xiaohan / Jingzhe 표 (JPL Horizons·Skyfield 산출)
//   교차 확인: 2024 입춘 2/4 17:27 KST (월력 절기표·언론 보도와 일치)
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { computeSaju, dayPillar, julianDayNumber, pillarName, sunLongitude } from './saju.ts';

const KASI_ILJIN = [
  ['1900-01-01', '甲戌'], ['1950-06-25', '辛卯'], ['1970-01-01', '辛巳'], ['1988-09-17', '乙亥'],
  ['1990-12-15', '甲寅'], ['1995-02-04', '丙寅'], ['1999-12-31', '丁巳'], ['2000-01-01', '戊午'],
  ['2000-02-29', '丁巳'], ['2010-07-15', '丙寅'], ['2023-01-01', '己未'], ['2024-02-04', '戊戌'],
  ['2025-02-03', '癸卯'], ['2025-02-04', '甲辰'], ['2026-10-22', '己巳'], ['2030-12-31', '庚子'],
  ['2023-03-06', '癸亥'], ['2024-01-06', '己巳'],
];

const ymd = s => s.split('-').map(Number);

test('일주 — 한국천문연구원 일진 18건과 일치', () => {
  for (const [date, expected] of KASI_ILJIN) {
    const [y, m, d] = ymd(date);
    assert.equal(pillarName(dayPillar(y, m, d)), expected, date);
  }
});

test('회귀: 2023-01-01 은 甲子가 아니라 己未 (JDN 2459946)', () => {
  assert.equal(julianDayNumber(2023, 1, 1), 2459946);
  assert.equal(pillarName(dayPillar(2023, 1, 1)), '己未');
});

// 절입 시각(UTC) — 이 순간 태양 황경이 목표 각도여야 한다
const TERMS = {
  315: ['2001-02-03 18:28', '2004-02-04 11:56', '2010-02-03 22:47', '2015-02-04 03:58', '2020-02-04 09:03',
    '2023-02-04 02:42', '2024-02-04 08:27', '2025-02-03 14:10', '2026-02-03 20:02', '2030-02-03 19:08'],
  285: ['2002-01-05 12:43', '2008-01-05 23:24', '2016-01-05 22:08', '2023-01-05 15:04', '2024-01-05 20:49',
    '2031-01-05 13:23'],
  345: ['2001-03-05 12:32', '2011-03-05 22:29', '2019-03-05 21:09', '2023-03-05 20:36', '2030-03-05 13:03'],
};

test('태양 황경 — 절입 시각 오차 0.012°(약 17분) 이내', () => {
  for (const [target, list] of Object.entries(TERMS)) {
    for (const s of list) {
      const [date, time] = s.split(' ');
      const [y, m, d] = ymd(date);
      const [hh, mm] = time.split(':').map(Number);
      const jd = julianDayNumber(y, m, d) - 0.5 + (hh + mm / 60) / 24;
      let diff = sunLongitude(jd) - Number(target);
      diff = ((diff + 540) % 360) - 180;
      assert.ok(Math.abs(diff) < 0.012, `${s} 황경 ${target}° 오차 ${diff.toFixed(4)}°`);
    }
  }
});

// [년, 월, 일, 시지(0=子…11=亥 | null), 기대 '년 월 일 시']
const FOUR_PILLARS = [
  // 2025 입춘 = 2025-02-03 23:10 KST. 亥時(대표 22:30)는 아직 甲辰년
  [2025, 2, 3, 11, '甲辰 丁丑 癸卯 癸亥'],
  [2025, 2, 3, 10, '甲辰 丁丑 癸卯 壬戌'],
  [2025, 2, 4, 0, '乙巳 戊寅 甲辰 甲子'],
  [2025, 2, 4, 6, '乙巳 戊寅 甲辰 庚午'],
  // 2024 입춘 = 2024-02-04 17:27 KST. 申時(16:30) 전 / 酉時(18:30) 후
  [2024, 2, 4, 8, '癸卯 乙丑 戊戌 庚申'],
  [2024, 2, 4, 9, '甲辰 丙寅 戊戌 辛酉'],
  // 1월 출생은 입춘 전이라 전년도 간지 (양력 년도로 보던 기존 버그)
  [2023, 1, 1, null, '壬寅 壬子 己未'],
  // 2024 소한 = 2024-01-06 05:49 KST. 寅時(04:30) 子月 / 辰時(08:30) 丑月
  [2024, 1, 6, 2, '癸卯 甲子 己巳 丙寅'],
  [2024, 1, 6, 4, '癸卯 乙丑 己巳 戊辰'],
  // 2023 경칩 = 2023-03-06 05:36 KST. 寅時 寅月 / 卯時 卯月
  [2023, 3, 6, 2, '癸卯 甲寅 癸亥 甲寅'],
  [2023, 3, 6, 3, '癸卯 乙卯 癸亥 乙卯'],
  // 자정 경계: 일진은 자정에 바뀜
  [1999, 12, 31, 11, '己卯 丙子 丁巳 辛亥'],
  [2000, 1, 1, 0, '己卯 丙子 戊午 壬子'],
  // 한여름 평범한 날 (윤년 2/29 포함)
  [2000, 2, 29, 6, '庚辰 戊寅 丁巳 丙午'],
  [1988, 9, 17, null, '戊辰 辛酉 乙亥'],
];

test('사주 4기둥 — 입춘·절기·자정 경계', () => {
  for (const [y, m, d, h, expected] of FOUR_PILLARS) {
    const s = computeSaju(y, m, d, h);
    const got = [s.year, s.month, s.day, s.hour].filter(Boolean).map(pillarName).join(' ');
    assert.equal(got, expected, `${y}-${m}-${d} 시지=${h}`);
  }
});
